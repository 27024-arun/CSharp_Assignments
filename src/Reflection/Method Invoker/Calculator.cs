namespace Reflection.Task3
{
    /// <summary>
    /// Performs mathematical operations.
    /// </summary>
    public class Calculator
    {
        /// <summary>
        /// Adds two numbers and displays their result.
        /// </summary>
        public void Add()
        {
            Console.WriteLine($"Addition: {10 + 20}");
        }

        /// <summary>
        /// Subtracts two numbers and displays their result.
        /// </summary>
        public void Subtract()
        {
            Console.WriteLine($"Subtraction: {10 - 20}");
        }

        /// <summary>
        /// Multiplies two numbers and displays their result.
        /// </summary>
        public void Multiplication()
        {
            Console.WriteLine($"Addition: {10 * 20}");
        }

        /// <summary>
        /// Divides two numbers and displays their result.
        /// </summary>
        public void Division()
        {
            Console.WriteLine($"Addition: {10 / 20}");
        }
    }
}
